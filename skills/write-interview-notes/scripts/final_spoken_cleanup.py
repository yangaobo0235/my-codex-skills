def clean_text(text: str) -> str:
    lines = []
    for line in text.splitlines():
        line = HEADING_REPLACEMENTS.get(line, line)
        prefix = "> " if line.startswith("> ") else ""
        body = line[2:] if prefix else line
        body = EXACT.get(body, body)
        for old, new in SUBSTRINGS.items():
            body = body.replace(old, new)
        if body == "如果你在项目里确实做过这一块，核心可以分为以下几点：":
            body = ""
        if body == "核心可以分为以下几点：":
            body = "可以从以下方面概括："
        body = body.replace("** **", "**")
        body = body.replace("；，", "；").replace("：，", "：")
        body = re.sub(r"^(### Q\d{2}\. .+?)有哪些高频追问？$", r"\1还需要注意什么？", body)
        body = body.replace("**高频追问：", "**进一步看：")
        body = re.sub(r"\*\*追问补充(\d+)：", r"**补充\1：", body)
        lines.append(prefix + body)
    output = "\n".join(lines)
    if text.endswith("\n"):
        output += "\n"
    return output


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("path", type=Path)
    args = parser.parse_args()
    files = [args.path] if args.path.is_file() else sorted(args.path.rglob("*.md"))
    changed = 0
    for path in files:
        raw = path.read_bytes()
        bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw.decode("utf-8-sig")
        output = clean_text(text)
        encoded = output.encode("utf-8")
        if bom:
            encoded = b"\xef\xbb\xbf" + encoded
        if encoded != raw:
            path.write_bytes(encoded)
            changed += 1
    print(f"Files changed: {changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
